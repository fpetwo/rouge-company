"""Writes src/core/golem-bases.ts (metal weapon bases an Iron Golem can be made from) from data/game-data.json."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
d = json.load(open(root / 'data' / 'game-data.json', encoding='utf-8'))
TYPES = ['Axe', 'Sword', 'Dagger', 'Mace', 'Hammer', 'Scepter', 'Polearm', 'Spear']
def rng(s):
    if not s: return None
    a, b = s.split('–'); return [int(a), int(b)]
rows = []
for w in d['weapons']:
    if w['type'] not in TYPES or w['class']: continue
    one = rng(w['oneHand'])
    rows.append({'code': w['code'], 'name': w['name'], 'type': w['type'], 'tier': w['tier'], 'one': one, 'wsm': w['speed']})
rows.sort(key=lambda r: (TYPES.index(r['type']), r['name']))
out = root / 'src' / 'core' / 'golem-bases.ts'
out.write_text('// Generated by scripts/gen_golem_bases.py from data/game-data.json – do not edit.\n'
  '// one = one-hand damage [min, max] (null: two-handed only, no damage transfers to the golem); wsm = weapon speed modifier.\n'
  'export interface GolemBase { code: string; name: string; type: string; tier: string; one: [number, number] | null; wsm: number }\n'
  f'export const GOLEM_BASES: GolemBase[] = {json.dumps(rows, ensure_ascii=False)};\n', encoding='utf-8')
print(len(rows), 'bases ->', out)
