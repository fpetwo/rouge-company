"""Writes src/core/merc-data.ts (Hell mercenaries, their weapon bases and skill tables) from blizzhackers/d2data.

Usage:  git clone --depth 1 https://github.com/blizzhackers/d2data /path/to/d2data
        python3 scripts/gen_merc_data.py /path/to/d2data/json

Values are copied from hireling.txt, weapons.txt and skills.txt (D2R tables, Reign of the Warlock).
"""
import json, sys
from pathlib import Path

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
load = lambda f: json.load(open(src / f, encoding='utf-8'))
strings = load('allstrings-eng.json')

# ---- Hell mercenaries (expansion rows, version 100) ----
ROWS = {
    'rogueFire': ('Rogue Scout', 'Fire - Hell'), 'rogueCold': ('Rogue Scout', 'Ice - Hell'),
    'a2Combat': ('Desert Mercenary', 'Comb-Hell'), 'a2Def': ('Desert Mercenary', 'Def-Hell'), 'a2Off': ('Desert Mercenary', 'Off-Hell'),
    'a2Thorns': ('Desert Mercenary', 'Thorns-Hell'), 'a2Freeze': ('Desert Mercenary', 'HolyFreeze-Hell'), 'a2Might': ('Desert Mercenary', 'Might-Hell'),
    'a3Fire': ('Eastern Sorceror', 'Fire-Hell'), 'a3Cold': ('Eastern Sorceror', 'Cold-Hell'), 'a3Ltng': ('Eastern Sorceror', 'Ltng-Hell'),
    'a5Bash': ('Barbarian', '2hs-Hell'), 'a5Frenzy': ('Barbarian', '1hs-Hell'),
}
hire = [r for r in load('hireling.json').values() if r.get('Version') == 100 and r.get('Difficulty') == 3]
mercs = {}
for key, (name, sub) in ROWS.items():
    r = next(x for x in hire if x['Hireling'] == name and x.get('*SubType') == sub)
    skills = []
    for i in range(1, 7):
        s = r.get(f'Skill{i}')
        if not s: continue
        skills.append({'skill': s, 'mode': r.get(f'Mode{i}') or 0, 'chance': r.get(f'Chance{i}') or 0, 'chancePerLvl': r.get(f'ChancePerLvl{i}') or 0,
                       'level': r.get(f'Level{i}') or 0, 'lvlPerLvl': r.get(f'LvlPerLvl{i}') or 0})
    mercs[key] = {'name': name, 'sub': sub, 'lvl': r['Level'], 'str': r['Str'], 'strPerLvl': r['Str/Lvl'], 'dex': r['Dex'], 'dexPerLvl': r['Dex/Lvl'],
                  'ar': r['AR'], 'arPerLvl': r['AR/Lvl'], 'dmgMin': r['Dmg-Min'], 'dmgMax': r['Dmg-Max'], 'dmgPerLvl': r['Dmg/Lvl'],
                  'defaultChance': r['DefaultChance'], 'skills': skills}

# ---- Weapon bases each merc can wield ----
weapons = [w for w in load('weapons.json').values() if w.get('code') and w.get('spawnable')]
def tier(w):
    return 'Elite' if w['code'] == w.get('ultracode') else 'Exceptional' if w['code'] == w.get('ubercode') else 'Normal'
GROUPS = {'bow': ('Bow', ['bow', 'abow']), 'pole': ('Polearm', ['pole']), 'spea': ('Spear', ['spea']), 'swor': ('Sword', ['swor'])}
bases = []
for g, (label, types) in GROUPS.items():
    for w in weapons:
        if w['type'] not in types: continue
        two = bool(w.get('2handed'))
        one_or_two = bool(w.get('1or2handed'))
        bases.append({
            'code': w['code'], 'name': strings.get(w.get('namestr', w['code']), w['name']), 'group': g, 'type': label, 'tier': tier(w),
            'one': [w['mindam'], w['maxdam']] if w.get('mindam') else None,
            'two': [w['2handmindam'], w['2handmaxdam']] if w.get('2handmindam') else None,
            'twoHanded': two and not one_or_two, 'oneOrTwo': one_or_two,
            'wsm': w.get('speed') or 0, 'strBonus': w.get('StrBonus') or 0, 'dexBonus': w.get('DexBonus') or 0,
            'reqStr': w.get('reqstr') or 0, 'reqDex': w.get('reqdex') or 0})
TIER = ['Normal', 'Exceptional', 'Elite']
bases.sort(key=lambda b: (list(GROUPS).index(b['group']), TIER.index(b['tier']), b['name']))

# ---- Skill tables for the skills mercs use ----
WANT = ['Inner Sight', 'Fire Arrow', 'Cold Arrow', 'Exploding Arrow', 'Freezing Arrow', 'Jab', 'Bash', 'Stun', 'Frenzy', 'Taunt',
        'Fire Bolt', 'Fire Ball', 'Glacial Spike', 'Ice Blast', 'Charged Bolt', 'Lightning']
FIELDS = ['ToHit', 'LevToHit', 'HitShift', 'SrcDam', 'EType', 'EMin', 'EMinLev1', 'EMinLev2', 'EMinLev3', 'EMinLev4', 'EMinLev5',
          'EMax', 'EMaxLev1', 'EMaxLev2', 'EMaxLev3', 'EMaxLev4', 'EMaxLev5', 'EDmgSymPerCalc', 'calc1', 'calc2', 'ToHitCalc',
          'Param1', 'Param2', 'Param3', 'Param4', 'Param5', 'Param6', 'Param7', 'Param8', 'reqlevel']
skills = {}
for r in load('skills.json').values():
    if r.get('skill') in WANT and r.get('skill') not in skills:
        skills[r['skill']] = {f: r[f] for f in FIELDS if r.get(f) not in (None, '')}
# Arrow conversion (missiles.txt: "% damage dealt as elemental" = dParam1 + dParam2 × (lvl − 1))
miss = {m['Missile']: m for m in load('missiles.json').values() if m.get('Missile')}
for skill, mis in (('Cold Arrow', 'coldarrow'), ('Fire Arrow', 'firearrow')):
    m = miss[mis]
    skills[skill]['conv'] = [m.get('dParam1') or 0, m.get('dParam2') or 0]

out = root / 'src' / 'core' / 'merc-data.ts'
out.write_text(
    '// Generated by scripts/gen_merc_data.py from blizzhackers/d2data (hireling.txt, weapons.txt, skills.txt, missiles.txt) – do not edit.\n'
    '// Hireling per-level stats: str/dex/damage in 1/8 per level, AR per level in full points, skill level = level + ⌊levels × lvlPerLvl / 32⌋.\n'
    'export interface MercSkillRow { skill: string; mode: number; chance: number; chancePerLvl: number; level: number; lvlPerLvl: number }\n'
    'export interface MercRow { name: string; sub: string; lvl: number; str: number; strPerLvl: number; dex: number; dexPerLvl: number; ar: number; arPerLvl: number; dmgMin: number; dmgMax: number; dmgPerLvl: number; defaultChance: number; skills: MercSkillRow[] }\n'
    'export interface MercBase { code: string; name: string; group: string; type: string; tier: string; one: [number, number] | null; two: [number, number] | null; twoHanded: boolean; oneOrTwo: boolean; wsm: number; strBonus: number; dexBonus: number; reqStr: number; reqDex: number }\n'
    'export type SkillRow = Record<string, number | string | number[]>;\n'
    f'export const MERC_ROWS: Record<string, MercRow> = {json.dumps(mercs, ensure_ascii=False)};\n'
    f'export const MERC_BASES: MercBase[] = {json.dumps(bases, ensure_ascii=False)};\n'
    f'export const SKILL_ROWS: Record<string, SkillRow> = {json.dumps(skills, ensure_ascii=False)};\n', encoding='utf-8')
print(len(mercs), 'mercs,', len(bases), 'bases,', len(skills), 'skills ->', out)
